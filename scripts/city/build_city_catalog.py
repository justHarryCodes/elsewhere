"""Builds packages/shared/src/city-catalog.ts from the Kenney city kits in apps/client/public/assets.

Measures every model's bounds (in kit units, where a road tile is 1 x 1) so the city generator in
packages/shared/src/city.ts can lay out roads, fit buildings onto lots and give them colliders without
loading any 3D files. Kit conventions (checked by rendering): building fronts face -Z.

Run again after adding models to a kit:
    python3 scripts/city/build_city_catalog.py
"""
import glob
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), '..', 'vehicles'))
from gltfscene import evaluate, load, union  # noqa: E402

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
PUBLIC = os.path.join(ROOT, 'apps', 'client', 'public')
OUT = os.path.join(ROOT, 'packages', 'shared', 'src', 'city-catalog.ts')

KITS = {
    'suburban': 'assets/buildings/kenney-city-kit-suburban',
    'commercial': 'assets/buildings/kenney-city-kit-commercial',
    'industrial': 'assets/buildings/kenney-city-kit-industrial',
    'roads': 'assets/roads/kenney-city-kit-roads',
}


def r(v):
    v = round(v, 3)
    return 0 if v == 0 else v


def main():
    lines = [
        '// GENERATED by scripts/city/build_city_catalog.py from the .glb files. Do not edit by hand.',
        '//',
        '// Bounds are in kit units (a road tile is 1 x 1), as the model is authored: fronts face -Z.',
        '',
        'export interface CityModel {',
        '  url: string;',
        '  min: [number, number, number];',
        '  max: [number, number, number];',
        '}',
        '',
        'export const CITY_MODELS = {',
    ]
    for kit, folder in KITS.items():
        for path in sorted(glob.glob(os.path.join(PUBLIC, folder, '**', '*.glb'), recursive=True)):
            name = os.path.splitext(os.path.basename(path))[0]
            lo, hi = union([n['box'] for n in evaluate(load(path))])
            url = '/' + os.path.relpath(path, PUBLIC).replace(os.sep, '/')
            lines.append(f'  "{kit}/{name}": {{ url: "{url}", min: [{r(lo[0])}, {r(lo[1])}, {r(lo[2])}], '
                         f'max: [{r(hi[0])}, {r(hi[1])}, {r(hi[2])}] }},')
    lines += ['} satisfies Record<string, CityModel>;', '', 'export type CityModelKey = keyof typeof CITY_MODELS;', '']
    open(OUT, 'w').write('\n'.join(lines))
    print('wrote', OUT, len(lines) - 16, 'models')


if __name__ == '__main__':
    main()
